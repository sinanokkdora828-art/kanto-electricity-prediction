import pandas as pd


# ==========================================
# ① 都道府県ごとの人口
# ==========================================

population = {
    "茨城県": 2810000,
    "栃木県": 1900000,
    "群馬県": 1900000,
    "埼玉県": 7300000,
    "千葉県": 6300000,
    "東京都": 14100000,
    "神奈川県": 9200000
}


# ==========================================
# ② JMAの予報気温から
#    都道府県ごとの平均気温を計算
# ==========================================

def calculate_forecast_average(df_forecast):

    print("\n==========================================")
    print("予報期間の平均気温を計算します")
    print("==========================================")

    # 都道府県ごとに気温の平均を計算
    df_average = (
        df_forecast
        .groupby("都道府県")
        .agg(
            予測気温=("気温", "mean")
        )
        .reset_index()
    )

    # ==========================================
    # 人口を追加
    # ==========================================

    df_average["人口"] = (
        df_average["都道府県"]
        .map(population)
    )

    print("\n予報期間の平均気温")

    print(
        df_average.to_string(index=False)
    )

    return df_average


# ==========================================
# ③ 機械学習モデルで
#    電力需要を予測
# ==========================================

def predict_electricity_demand(
    model,
    df_forecast
):

    print("\n==========================================")
    print("将来の電力需要を予測します")
    print("==========================================")

    # ==========================================
    # 機械学習モデルに入力するデータを作成
    # ==========================================

    X_future = pd.DataFrame({

        # 予報期間の平均気温
        "気温": df_forecast["予測気温"],

        # 気温の二乗
        "気温²": (
            df_forecast["予測気温"] ** 2
        ),

        # 人口
        "人口": df_forecast["人口"]

    })

    print("\n機械学習モデルへの入力データ")

    print(
        X_future.to_string(index=False)
    )

    # ==========================================
    # 機械学習モデルで電力需要を予測
    # ==========================================

    predicted_demand = model.predict(
        X_future
    )

    # ==========================================
    # 予測結果を元のDataFrameに追加
    # ==========================================

    df_result = df_forecast.copy()

    df_result["予測電力需要_Wh"] = (
        predicted_demand
    )

    # 兆Whに変換
    df_result["予測電力需要_兆Wh"] = (
        df_result["予測電力需要_Wh"] / 1e12
    )

    # ==========================================
    # 予測結果を表示
    # ==========================================

    print("\n==========================================")
    print("予測結果")
    print("==========================================")

    print(
        df_result[
            [
                "都道府県",
                "予測気温",
                "人口",
                "予測電力需要_Wh",
                "予測電力需要_兆Wh"
            ]
        ].to_string(index=False)
    )

    return df_result
